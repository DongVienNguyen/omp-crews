import assert from 'node:assert/strict';
import {createHash} from 'node:crypto';
import {prepareHostBinding,assertHostBinding,createHostLedger,bindingDigest} from './host-binding.mjs';

const schemas=[1e-6,1e21,-0,1/3,Number.MIN_VALUE,Number.MAX_VALUE].map(minimum=>({type:'number',minimum}));
schemas.push({type:'object',properties:{'\ue000':{const:'BMP'},'\u{10000}':{const:'astral'},'é':{enum:[null,true,false,0,'\u0000\b\t\n\f\r"\\\u2028\u2029\ud800\udc00\udfff']}},additionalProperties:false});
const cases=schemas.map(schema=>{
 const prepared=prepareHostBinding({tools:[{name:'workspace_read',parameters:schema,execute:async()=>({content:[]})}],resultSchema:schema,limits:{max_output_tokens:4,max_input_bytes:128,max_output_bytes:256},deadline:4102444800000});
 assert.equal(bindingDigest(JSON.parse(JSON.stringify(prepared.descriptor))),prepared.digest,'JSON transport preserves digest, including negative zero');
 return {descriptor:prepared.descriptor,digest:prepared.digest};
});
assert.equal(bindingDigest(1),createHash('sha256').update('["number","3ff0000000000000"]').digest('hex'));
assert.equal(bindingDigest(-0),bindingDigest(0));
assert.equal(bindingDigest({'\ue000':1,'\u{10000}':2}),bindingDigest({'\u{10000}':2,'\ue000':1}));
assert.equal(bindingDigest('\u{10000}'),bindingDigest('\ud800\udc00'));
assert.notEqual(bindingDigest([1]),bindingDigest({'0':1}));
assert.notEqual(bindingDigest(true),bindingDigest(1));
assert.notEqual(bindingDigest(null),bindingDigest('null'));
for(const value of [NaN,Infinity,-Infinity,undefined,{missing:undefined},new Date()])assert.throws(()=>bindingDigest(value),/JSON/);
const tool={name:'workspace_read',parameters:{type:'object',properties:{path:{type:'string'}},required:['path']},execute:async()=>({content:[]})};
const options={tools:[tool],resultSchema:{type:'object',properties:{answer:{type:'string'}},required:['answer'],additionalProperties:false},limits:{max_output_tokens:4,max_input_bytes:128,max_output_bytes:256},deadline:Date.now()+60000};
const binding=prepareHostBinding(options);
assert.equal(binding.tools[0],tool,'original tool closure retained');
assert.equal(binding.digest,bindingDigest(binding.descriptor));
assert.equal(JSON.stringify(binding.descriptor).includes('execute'),false);
assertHostBinding(binding,{descriptor:binding.descriptor,digest:binding.digest});
assert.throws(()=>assertHostBinding(binding,{descriptor:binding.descriptor,digest:'forged'}),/mismatch/);
const tampered=structuredClone(binding.descriptor);tampered.result_schema.additionalProperties=true;
assert.throws(()=>assertHostBinding(binding,{descriptor:tampered,digest:binding.digest}),/mismatch/);
assert.throws(()=>assertHostBinding({...binding,descriptor:tampered},{descriptor:binding.descriptor,digest:binding.digest}),/mismatch/);
const expired=prepareHostBinding({...options,deadline:Date.now()+60000});
expired.descriptor.deadline=1;expired.digest=bindingDigest(expired.descriptor);
assert.throws(()=>assertHostBinding(expired,{descriptor:expired.descriptor,digest:expired.digest}),/expired/);
assert.throws(()=>prepareHostBinding({...options,tools:[{...tool,name:'task'}]}),/Invalid/);
assert.throws(()=>prepareHostBinding({...options,tools:[tool,tool]}),/Invalid/);
assert.throws(()=>prepareHostBinding({...options,deadline:0}),/deadline/);
assert.throws(()=>prepareHostBinding({...options,limits:{...options.limits,max_output_tokens:0}}),/budget/);
const ledger=createHostLedger(binding);
assert.equal(ledger.request({max_tokens:100}).max_tokens,4);
ledger.observe({content:[],usage:{output:3}});
assert.equal(ledger.request({max_tokens:100}).max_tokens,1);
assert.throws(()=>ledger.request({text:'é'.repeat(100)}),/input_byte_limit/);
ledger.observe({content:[],usage:{output:1}});
assert.throws(()=>ledger.request({}),/output_budget_exhausted/);
const unknown=createHostLedger(binding);
assert.throws(()=>unknown.observe({content:[{type:'text',text:'x'}]}),/output_usage_unknown/);
assert.throws(()=>unknown.request({}),/output_usage_unknown/);
const changed={...binding,tools:[{...tool,parameters:{type:'string'}}]};
assert.throws(()=>assertHostBinding(changed,{descriptor:binding.descriptor,digest:binding.digest}),/schema changed/);
console.log(process.argv.includes('--binding-cases')?JSON.stringify(cases):'host binding checks passed (7 cross-language fixtures)');
