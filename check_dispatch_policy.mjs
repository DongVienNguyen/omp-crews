import assert from 'node:assert/strict';
import { createPlanRecovery } from './routing-policy.mjs';
const guard = createPlanRecovery();
assert.equal(guard.blockReason(), null);
guard.begin('a');
assert.match(guard.blockReason(), /pending/);
guard.result('unrelated', false);
assert.match(guard.blockReason(), /pending/);
guard.result('a', true);
assert.match(guard.blockReason(), /Repair crew_plan/);
guard.begin('b');
guard.result('b', false);
assert.equal(guard.blockReason(), null);
guard.begin('c');
guard.begin('d');
guard.result('c', false);
assert.match(guard.blockReason(), /pending/);
guard.result('d', true);
assert.match(guard.blockReason(), /Repair crew_plan/);
guard.reset();
guard.begin('e');
guard.begin('f');
guard.result('e', true);
guard.result('f', false);
assert.match(guard.blockReason(), /Repair crew_plan/);
guard.begin('g');
guard.result('g', false);
assert.equal(guard.blockReason(), null);
guard.reset();
assert.equal(guard.blockReason(), null);
console.log('PASS: pending/failed plan blocks native fallback; corrected plan and new user turn recover');
